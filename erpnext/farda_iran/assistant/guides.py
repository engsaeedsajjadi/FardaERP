_ARABIC = str.maketrans({"ي": "ی", "ى": "ی", "ك": "ک", "ة": "ه", "أ": "ا", "إ": "ا", "آ": "ا", "ؤ": "و", "ۀ": "ه"})
_DIACRITICS = re.compile("[ً-ٰٟـ]")
_NON_WORD = re.compile(r"[^\w\s]", re.UNICODE)
_SPACES = re.compile(r"\s+")

STOPWORDS = frozenset(
	"""چطور چطوری چگونه چجوری چه چی چیه کجا کجاست باید میشه می شه میتونم می توانم بکنم کنم کنیم کرد کردن
	انجام دادن بدم بدهم داد دهم را رو به با از در که این اون آن یه یک برای واسه تا هم و یا اگه اگر ام است هست
	میخوام می خواهم میخواستم لطفا لطفاً من ما ی نمیدونم نمی دانم بلد نیستم توی تو مرحله مراحل راهنمایی کار""".split()
)


def normalize(text: str) -> str:
	"""Unify Arabic/Persian letters, drop diacritics/punctuation, ZWNJ → space."""
	text = (text or "").translate(_ARABIC).replace("‌", " ").replace("‏", " ").lower()
	text = _DIACRITICS.sub("", text)
	text = _NON_WORD.sub(" ", text)
	return _SPACES.sub(" ", text).strip()


def tokens(text: str) -> list[str]:
	return [t for t in normalize(text).split() if t not in STOPWORDS and len(t) > 1]


def _token_match(a: str, b: str) -> bool:
	"""Loose Persian match: equal, or one is a prefix of the other (فاکتور/فاکتورها)."""
	if a == b:
		return True
	short, long_ = (a, b) if len(a) <= len(b) else (b, a)
	return len(short) >= 3 and long_.startswith(short)


def score_guide(guide: dict, question: str, doctype: str | None = None) -> float:
	q_norm = " " + normalize(question) + " "
	q_tokens = tokens(question)
	score = 0.0
	for phrase in guide["keywords"]:
		p = normalize(phrase)
		if p and ((" " + p + " ") in q_norm or (len(p) >= 5 and p in q_norm)):
			score += 2.0 + len(p.split())
	title = normalize(guide["title"])
	if title and title in q_norm:
		score += 6.0  # the user picked this guide (related chip) or typed its title
	vocab = set(tokens(guide["title"]))
	for phrase in guide["keywords"]:
		vocab.update(tokens(phrase))
	matched = sum(1 for t in q_tokens if any(_token_match(t, v) for v in vocab))
	score += matched
	if doctype and doctype in guide.get("doctypes", ()):
		score += 1.5 if score > 0 else 0.5
	return score


def search(question: str, doctype: str | None = None, limit: int = 3, min_score: float = 2.0) -> list[dict]:
	"""Best-matching guides, highest score first (empty when nothing is close)."""
	scored = [(score_guide(g, question, doctype), i, g) for i, g in enumerate(GUIDES)]
	scored = [s for s in scored if s[0] >= min_score]
	scored.sort(key=lambda s: (-s[0], s[1]))
	return [g for _, _, g in scored[:limit]]


def suggestions_for(doctype: str | None) -> list[str]:
	return list(SUGGESTIONS_BY_DOCTYPE.get(doctype or "", DEFAULT_SUGGESTIONS))


def guide_as_text(guide: dict) -> str:
	"""Plain-text rendering used both as AI context and as the offline answer."""
	lines = [guide["title"]]
	lines += [f"{i}. {s}" for i, s in enumerate(guide["steps"], 1)]
	for t in guide.get("tips", ()):
		lines.append(f"نکته: {t}")
	return "\n".join(lines)
